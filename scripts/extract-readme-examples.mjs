#!/usr/bin/env node
/**
 * README example extraction — every fenced code block in README.md becomes an
 * executable e2e case. No example left manual-only (Phase 6).
 *
 * Modes per block:
 *   run         — fragment operating on a live `map` (uses map./bkoigl./new bkoigl)
 *   map-create  — fragment constructing its own bkoigl.Map (gets a fresh container)
 *   import      — static import statements — verified via dynamic import
 *   expression  — config/option object documentation — validated as a JS expression
 *   skip        — not runnable here (install commands, CDN snippets, React JSX)
 *
 * Output: tests/e2e/app/readme-examples.js (generated, gitignored) — the e2e
 * host imports it and runs every `run`/`map-create`/`expression` case against
 * the BUILT dist with a real API key. README bytes stay untouched; transforms
 * apply only to the extracted copies (const→var for duplicate declarations,
 * placeholder key → real key, container id → fresh div).
 *
 * Usage: node scripts/extract-readme-examples.mjs [--check]
 *   --check: exit 1 if the generated module is stale (CI guard)
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const repoRoot = path.resolve(fileURLToPath(import.meta.url), '../..')
const outPath = path.join(repoRoot, 'tests/e2e/app/readme-examples.js')

const md = fs.readFileSync(path.join(repoRoot, 'README.md'), 'utf8')
const blocks = [...md.matchAll(/^```([^\n]*)\n([\s\S]*?)\n```$/gm)]

const examples = []
blocks.forEach(([, lang, raw], i) => {
  const id = `Example${String(i).padStart(2, '0')}`
  const code = raw.trimEnd()

  if (lang === 'bash' || lang === 'sh') {
    examples.push({ id, lang, mode: 'skip', reason: 'install command' })
    return
  }
  if (lang === 'html') {
    // CDN snippets are two <link>/<script> lines pointing at unpkg — the same
    // artifact contract is already covered by umd.html + formats.spec.
    if (!code.includes('<!DOCTYPE')) {
      examples.push({ id, lang, mode: 'skip', reason: 'CDN snippet (covered by formats.spec)' })
      return
    }
    // Full vanilla HTML page → extract the app <script> body as a map-create.
    const scripts = [...code.matchAll(/<script>([\s\S]*?)<\/script>/g)].map(m => m[1])
    const body = scripts.filter(s => s.includes('bkoigl')).join('\n')
    examples.push({
      id,
      lang,
      mode: 'map-create',
      code: body.replace(/\b(const|let) /g, 'var '),
    })
    return
  }
  if (lang.startsWith('typescript') || lang === 'tsx' || lang === 'ts') {
    // React/Next JSX consumer example — this repo has no React runtime.
    examples.push({ id, lang, mode: 'skip', reason: 'React JSX consumer example' })
    return
  }
  // Static import statement block — exercised by dynamic import in the runner.
  if (/^import /m.test(code)) {
    examples.push({ id, lang, mode: 'import', code })
    return
  }
  // javascript / unlabeled blocks
  if (/\bmap\.|\bbkoigl\b|new Map\(/.test(code)) {
    examples.push({ id, lang, mode: 'run', code: code.replace(/\b(const|let) /g, 'var ') })
    return
  }
  // Option/config documentation — validate as an expression.
  examples.push({ id, lang, mode: 'expression', code })
})

const counts = examples.reduce((a, e) => ((a[e.mode] = (a[e.mode] || 0) + 1), a), {})
console.log('[readme-examples]', examples.length, 'blocks:', JSON.stringify(counts))
for (const e of examples) {
  if (e.mode === 'skip') console.log(`  ${e.id}: SKIP — ${e.reason}`)
}

// Serialize as an ES module the e2e host imports. Function bodies are emitted
// via JSON-stringified source so nothing executes at import time.
const moduleSrc = `// GENERATED by scripts/extract-readme-examples.mjs — do not edit.
// Source of truth: README.md fenced blocks. Re-run the extractor to refresh.
export const README_EXAMPLES = ${JSON.stringify(examples, null, 2)}
`

if (process.argv.includes('--check') && fs.existsSync(outPath)) {
  if (fs.readFileSync(outPath, 'utf8') !== moduleSrc) {
    console.error('[readme-examples] STALE — run: node scripts/extract-readme-examples.mjs')
    process.exit(1)
  }
  console.log('[readme-examples] up to date')
} else {
  fs.writeFileSync(outPath, moduleSrc)
  console.log('[readme-examples] wrote', path.relative(repoRoot, outPath))
}
